#!/usr/bin/env node
'use strict';

// Offline authoring: scan → numerical readings → aligned matrix → database.
// The film crosses a stationary beam at constant speed. A reading cannot appear
// before its source frame reaches the beam. Digits are abstract visual material,
// not labelled benchmark results. No runtime frame calculations or dependencies.
const fs = require('node:fs');
const path = require('node:path');
const CSS = path.resolve(__dirname, '../css/project-motion/encoding.css');
const HTML = path.resolve(__dirname, '../assets/project-motion/encoding.html');
const DURATION = 22;
const SCAN_START = 2.8;
const FRAME_TIME = 1.2;
const READINGS = [
  ['0147', '6820', '3951', '2408'],
  ['7316', '0284', '5619', '4032'],
  ['2850', '9173', '0462', '6381'],
  ['4609', '1327', '8054', '2796'],
  ['9031', '5748', '2160', '3875']
];
const EASE = 'cubic-bezier(0.77, 0, 0.175, 1)';
const OUT = 'cubic-bezier(0.23, 1, 0.32, 1)';
const selector = '.project-art[data-motion="encoding"][data-running]';
const percent = (time) => `${Number((time / DURATION * 100).toFixed(6))}%`;
const round = (value) => Number(value.toFixed(4));
function replaceSection(file, marker, content) {
  const source = fs.readFileSync(file, 'utf8');
  const html = file.endsWith('.html');
  const start = html ? `<!-- ${marker}:start -->` : `/* ${marker}:start */`;
  const end = html ? `<!-- ${marker}:end -->` : `/* ${marker}:end */`;
  const from = source.indexOf(start);
  const to = source.indexOf(end);
  if (from < 0 || to < from) throw new Error(`Missing ${marker} source markers`);
  fs.writeFileSync(file, source.slice(0, from) + start + '\n' + content + '\n' + source.slice(to));
}
function transform(x, y, rotation = 0, scaleX = 1, skew = 0) {
  return `translate(${round(x)}px, ${round(y)}px) rotate(${round(rotation)}deg) scale(${round(scaleX)}, 1) skewY(${round(skew)}deg)`;
}
function databasePosition(row, column) {
  const angle = [-52, -18, 18, 52][column] * Math.PI / 180;
  const tier = Math.floor(row / 2);
  const withinTier = row === 4 ? 11.5 : row % 2 ? 19 : 4;
  return transform(250 + 88 * Math.sin(angle) - 17,
    94 + tier * 57 + 14 * Math.cos(angle) + withinTier,
    0, 0.85 + Math.cos(angle) * 0.15, -Math.sin(angle) * 12);
}
const source = [];
const css = ['/* Generated by scripts/build-film-poses.js. Timing is authored above. */'];
function animation(className, name, frames) {
  css.push(`${selector} .${className} { animation: ${name} ${DURATION}s linear infinite; }`, `@keyframes ${name} {`);
  for (const [times, declarations] of frames) {
    const points = Array.isArray(times) ? times : [times];
    css.push(`  ${points.map(percent).join(', ')} { ${declarations} }`);
  }
  css.push('}');
}

// Leading frame starts with its left edge at x250; each 76px frame takes 1.2s.
animation('film-strip', 'film-inspection-feed', [
  [[0, 1.5], `transform: translateX(0) rotate(-7deg); opacity: 1; animation-timing-function: ${EASE};`],
  [2.8, 'transform: translateX(190px) rotate(0deg); opacity: 1;'],
  [8.8, 'transform: translateX(-190px) rotate(0deg); opacity: 1;'],
  [9.6, 'transform: translateX(-300px) rotate(0deg); opacity: 0;'],
  [20.3, `transform: translateX(-20px) rotate(-7deg); opacity: 0; animation-timing-function: ${OUT};`],
  [22, 'transform: translateX(0) rotate(-7deg); opacity: 1;']
]);
animation('film-scanner', 'film-inspection-beam', [
  [[0, 2.6], 'opacity: 0;'], [[2.8, 8.8], 'opacity: 1;'], [[9.15, 22], 'opacity: 0;']
]);
animation('film-grid', 'film-matrix', [
  [[0, 9.8], `opacity: 0; transform: translateY(112px) scaleY(.7727); animation-timing-function: ${EASE};`],
  [[11.5, 13], `opacity: .72; transform: translateY(0) scaleY(1); animation-timing-function: ${EASE};`],
  [[14.2, 22], 'opacity: 0; transform: translateY(0) scaleY(1);']
]);
animation('film-database', 'film-matrix-depth', [
  [[0, 12.98], 'opacity: 0;'], [[13, 19], 'opacity: 1;'], [[20.2, 22], 'opacity: 0;']
]);
// Three existing table rules expand into elliptical lids while the stored rows
// curve onto the emerging walls. The database grows out of the matrix geometry.
[10, -3, -16].forEach((offset, tier) => animation(`film-db-lid-${tier}`, `film-db-lid-${tier}`, [
  [[0, 13], `transform: translate(3px, ${offset}px) scale(1.1023, .025); animation-timing-function: ${EASE};`],
  [[15.5, 22], 'transform: translate(0, 0) scale(1, 1);']
]));
animation('film-db-shell', 'film-db-walls', [
  [[0, 13], `opacity: 0; animation-timing-function: ${EASE};`], [[15.5, 22], 'opacity: 1;']
]);
animation('film-database-shadow', 'film-matrix-shadow', [
  [[0, 13], 'opacity: 0;'], [[15.5, 19], 'opacity: 1;'], [[20.2, 22], 'opacity: 0;']
]);

READINGS.forEach((row, rowIndex) => row.forEach((digits, column) => {
  const name = `film-reading-${rowIndex}-${column}`;
  // At .3s, the beam has inspected 19px of its source frame, beyond the border.
  const release = SCAN_START + rowIndex * FRAME_TIME + 0.3 + column * 0.25;
  const landing = release + 0.78;
  const x = 164 + column * 48.5;
  const y = 224 + rowIndex * 17;
  const bank = (column - 1.5) * 4;
  const first = transform(251, 204, bank);
  const lift = transform(276, 204, bank);
  const rail = transform(369, 204, 0);
  const turn = transform(369, y, 0);
  const landed = transform(x, y);
  const matrix = transform(x, 112 + rowIndex * 22);
  const database = databasePosition(rowIndex, column);
  source.push(`<span class="film-readout ${name}" aria-hidden="true">${digits}<span class="film-readout-flash" aria-hidden="true">${digits}</span></span>`);
  animation(name, name, [
    [[0, release], `opacity: 0; transform: ${first};`],
    [release + 0.07, `opacity: 1; transform: ${lift};`],
    [release + 0.16, `opacity: 1; transform: ${rail};`],
    [release + 0.24, `opacity: 1; transform: ${turn}; animation-timing-function: ${OUT};`],
    [[landing, 9.8], `opacity: 1; transform: ${landed}; animation-timing-function: ${EASE};`],
    [[11.5, 13], `opacity: 1; transform: ${matrix}; animation-timing-function: ${EASE};`],
    [[14.2, 19], `opacity: 1; transform: ${database};`],
    [[20.2, 22], `opacity: 0; transform: ${database};`]
  ]);
  // Orange travels with the output, then resolves into ink when it is filed.
  css.push(`${selector} .${name} .film-readout-flash { animation: ${name}-ink ${DURATION}s linear infinite; }`);
  css.push(`@keyframes ${name}-ink {`,
    `  0%, ${percent(release + 0.25)} { opacity: 1; }`,
    `  ${percent(landing)}, 100% { opacity: 0; }`, '}');
}));
replaceSection(HTML, 'film-readings', source.join('\n'));
replaceSection(CSS, 'film-poses', css.join('\n'));
console.log('Generated 22s film inspection: 5 scanned frames → 20 readings → matrix → database.');
