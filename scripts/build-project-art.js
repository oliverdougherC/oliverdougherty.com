#!/usr/bin/env node
// Keep both static homepages synchronized from the four authored motion studies.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const studies = [
  ['Encoding_Database', 'encoding', 'Film passes through an inspection beam; numerical readings settle into a grid that becomes a database.'],
  ['BetterVMAF', 'vmaf', 'A fine comparison line reveals coarse and detailed versions of an ASCII planet.'],
  ['Keiri', 'keiri', 'A kept hand is surrounded by the equally possible outcomes of a two-die reroll, followed by a random observed result.'],
  ['Lyra', 'lyra', 'A passage about period and frequency is annotated, becomes an equation and waveform, and recalls a missing term.'],
];
for (const entry of ['index.html', 'mobile/index.html']) {
  const file = path.join(root, entry);
  let html = fs.readFileSync(file, 'utf8');
  for (const [project, name, description] of studies) {
    const start = html.indexOf(`<article class="project-entry" data-project="${project}">`);
    assert(start >= 0, `Missing ${project} in ${entry}`);
    const end = html.indexOf('</article>', start);
    const article = html.slice(start, end);
    const previous = article.search(/<div\b[^>]*class="project-art\b/);
    assert(previous >= 0, `Missing visual slot for ${project}`);
    const fragment = fs.readFileSync(path.join(root, 'assets/project-motion', `${name}.html`), 'utf8').trimEnd();
    const visual = `<div class="project-art" data-motion="${name}" role="img" aria-label="${description}">\n              <div class="motion-stage">\n${fragment}\n              </div>\n            </div>\n          `;
    html = html.slice(0, start) + article.slice(0, previous) + visual + html.slice(end);
  }
  fs.writeFileSync(file, html);
}
const css = ['/* Generated by npm run build:project-art. Edit css/project-motion/*.css. */',
  fs.readFileSync(path.join(root, 'css/project-motion/base.css'), 'utf8'),
  ...studies.map(([, name]) => fs.readFileSync(path.join(root, 'css/project-motion', `${name}.css`), 'utf8')),
  `.project-art * { animation-play-state: paused !important; }\n.project-art[data-running="true"] * { animation-play-state: running !important; }\n@media (prefers-reduced-motion: reduce) { .project-art * { animation: none !important; } }\n`].join('\n');
fs.writeFileSync(path.join(root, 'css/project-motion.css'), css);
console.log('Embedded four motion studies in both homepages; built their shared stylesheet.');
